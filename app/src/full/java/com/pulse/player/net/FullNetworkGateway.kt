package com.pulse.player.net

import android.content.Context
import android.util.Base64
import android.util.Log
import com.pulse.player.data.settings.SettingsStore
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.io.FileOutputStream
import java.util.concurrent.TimeUnit

/** Full-flavor HTTP implementation. Every request is gated here. */
class FullNetworkGateway(
    private val context: Context,
    private val settings: SettingsStore
) : NetworkGateway {
    private val client by lazy {
        OkHttpClient.Builder()
            .connectTimeout(10, TimeUnit.SECONDS)
            .readTimeout(120, TimeUnit.SECONDS)
            .writeTimeout(60, TimeUnit.SECONDS)
            .build()
    }

    override suspend fun transcribeAudio(
        audioFile: File,
        apiKey: String,
        customPrompt: String?
    ): Result<TranscriptionResult> = withContext(Dispatchers.IO) {
        gated { 
            require(apiKey.isNotBlank()) { "Gemini API key is missing. Configure it in Pulse Settings." }
            require(audioFile.exists() && audioFile.length() > 0) { "The selected audio file is empty or unavailable." }
            val mimeType = when (audioFile.extension.lowercase()) {
                "m4a", "mp4" -> "audio/mp4"
                "mp3" -> "audio/mp3"
                "wav" -> "audio/wav"
                "ogg" -> "audio/ogg"
                else -> "audio/mp4"
            }
            val requestJson = JSONObject().apply {
                put("contents", JSONArray().put(JSONObject().apply {
                    put("parts", JSONArray()
                        .put(JSONObject().put("inlineData", JSONObject()
                            .put("mimeType", mimeType)
                            .put("data", Base64.encodeToString(audioFile.readBytes(), Base64.NO_WRAP))))
                        .put(JSONObject().put("text", customPrompt?.ifBlank { null }
                            ?: "Transcribe this audio accurately with punctuation and line breaks.")))
                }))
            }
            val model = "gemini-3.5-transcribe"
            val response = executeGenerateContent(model, requestJson.toString(), apiKey)
                .recoverCatching { executeGenerateContent("gemini-3.8-flash", requestJson.toString(), apiKey).getOrThrow() }
                .getOrThrow()
            TranscriptionResult(response, model)
        }
    }

    override suspend fun generateMusic(
        context: Context,
        prompt: String,
        modelName: String,
        apiKey: String
    ): Result<GeneratedMusicResult> = withContext(Dispatchers.IO) {
        gated {
            require(apiKey.isNotBlank()) { "Gemini API key is missing. Configure it in Pulse Settings." }
            require(prompt.isNotBlank()) { "Enter a musical description before generating audio." }
            val model = if (modelName == "lyria-3-pro-preview") modelName else "lyria-3-clip-preview"
            val body = JSONObject().put("contents", JSONArray().put(JSONObject().put(
                "parts", JSONArray().put(JSONObject().put("text", prompt.trim()))
            ))).toString()
            val response = executeRequest(model, body, apiKey)
            val json = JSONObject(response)
            val parts = json.optJSONArray("candidates")?.optJSONObject(0)
                ?.optJSONObject("content")?.optJSONArray("parts")
                ?: error("The provider returned no audio content.")
            var audioBytes: ByteArray? = null
            var description = ""
            for (index in 0 until parts.length()) {
                val part = parts.getJSONObject(index)
                description += part.optString("text").takeIf { it.isNotBlank() }?.plus("\n").orEmpty()
                part.optJSONObject("inlineData")?.optString("data")?.takeIf { it.isNotBlank() }?.let {
                    audioBytes = Base64.decode(it, Base64.DEFAULT)
                }
            }
            val bytes = audioBytes?.takeIf { it.isNotEmpty() } ?: error("The provider returned no audio data.")
            val dir = File(context.filesDir, "ai_music").apply { mkdirs() }
            val timestamp = System.currentTimeMillis()
            val title = prompt.take(30).replace(Regex("[^a-zA-Z0-9 ]"), "").trim().ifBlank { "AI Creation $timestamp" }
            val file = File(dir, "lyria_$timestamp.mp3")
            FileOutputStream(file).use { it.write(bytes) }
            GeneratedMusicResult(file, title, description.trim().ifBlank { "Generated by the configured provider" }, prompt, model)
        }
    }

    private suspend fun <T> gated(block: suspend () -> T): Result<T> {
        if (!settings.onlineFeaturesEnabled.first()) {
            return Result.failure(IllegalStateException("Online features are off. Enable them in Settings before connecting."))
        }
        if (settings.offlineOnlyMode.first()) {
            return Result.failure(IllegalStateException("Offline-only mode is enabled. No network request was made."))
        }
        return runCatching { block() }
    }

    private fun executeGenerateContent(model: String, jsonBody: String, apiKey: String): Result<String> =
        runCatching { executeRequest(model, jsonBody, apiKey) }

    private fun executeRequest(model: String, jsonBody: String, apiKey: String): String {
        val request = Request.Builder()
            .url("https://generativelanguage.googleapis.com/v1beta/models/$model:generateContent?key=$apiKey")
            .post(jsonBody.toRequestBody("application/json; charset=utf-8".toMediaType()))
            .build()
        client.newCall(request).execute().use { response ->
            val body = response.body?.string().orEmpty()
            if (!response.isSuccessful) {
                Log.w("FullNetworkGateway", "Provider request failed with HTTP ${response.code}")
                error(parseErrorMessage(body))
            }
            val parts = JSONObject(body).optJSONArray("candidates")?.optJSONObject(0)
                ?.optJSONObject("content")?.optJSONArray("parts")
                ?: error("The provider returned no content.")
            return buildString {
                for (index in 0 until parts.length()) append(parts.getJSONObject(index).optString("text"))
            }.trim().ifBlank { error("The provider returned empty content.") }
        }
    }

    private fun parseErrorMessage(body: String): String = runCatching {
        JSONObject(body).optJSONObject("error")?.optString("message")
    }.getOrNull()?.takeIf { it.isNotBlank() } ?: "The online provider rejected the request."
}
